#!/usr/bin/env node
/**
 * Generates src/data/dictionary/words.en.ts from a SCOWL release.
 *
 * Usage:
 *   node scripts/build-dictionary.mjs <path-to-scowl>/final
 *
 * SCOWL (Spell Checker Oriented Word Lists) by Kevin Atkinson:
 *   http://wordlist.aspell.net/  (licence copied to src/data/dictionary/LICENSE-SCOWL.txt)
 *
 * Words are grouped into tiers by SCOWL size level:
 *   tier 1 (common)   sizes 10–35
 *   tier 2 (standard) sizes 40–50
 *   tier 3 (rare)     sizes 55–70
 * Only lowercase a–z words of MIN_LEN..MAX_LEN letters are kept; proper nouns,
 * abbreviations and contractions live in separate SCOWL files and are skipped.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const MIN_LEN = 3;
const MAX_LEN = 6;
const TIERS = [
  { tier: 1, sizes: [10, 20, 35] },
  { tier: 2, sizes: [40, 50] },
  { tier: 3, sizes: [55, 60, 70] },
];
const SPELLINGS = ['english', 'american', 'british'];

const finalDir = process.argv[2];
if (!finalDir || !fs.existsSync(finalDir)) {
  console.error('Usage: node scripts/build-dictionary.mjs <scowl>/final');
  process.exit(1);
}

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const blocklist = new Set(
  fs
    .readFileSync(path.join(here, 'blocklist.txt'), 'utf8')
    .split(/\r?\n/)
    .map((w) => w.trim().toLowerCase())
    .filter((w) => w && !w.startsWith('#')),
);

const seen = new Map();
for (const { tier, sizes } of TIERS) {
  for (const size of sizes) {
    for (const spelling of SPELLINGS) {
      const file = path.join(finalDir, `${spelling}-words.${size}`);
      if (!fs.existsSync(file)) continue;
      const text = fs.readFileSync(file, 'latin1');
      for (const raw of text.split(/\r?\n/)) {
        const w = raw.trim();
        if (w.length < MIN_LEN || w.length > MAX_LEN) continue;
        if (!/^[a-z]+$/.test(w)) continue;
        if (blocklist.has(w)) continue;
        if (!seen.has(w)) seen.set(w, tier);
      }
    }
  }
}

const byTier = { 1: [], 2: [], 3: [] };
for (const [w, t] of seen) byTier[t].push(w);
for (const t of [1, 2, 3]) byTier[t].sort();

const outDir = path.join(root, 'src', 'data', 'dictionary');
fs.mkdirSync(outDir, { recursive: true });
const out = `// AUTO-GENERATED by scripts/build-dictionary.mjs from SCOWL. Do not edit by hand.
// Source: SCOWL 2020.12.07, http://wordlist.aspell.net/ — see LICENSE-SCOWL.txt.
// Words: ${seen.size} (tier1 ${byTier[1].length}, tier2 ${byTier[2].length}, tier3 ${byTier[3].length}); lengths ${MIN_LEN}-${MAX_LEN}.

export const EN_WORDS_TIER1 = ${JSON.stringify(byTier[1].join(' '))};
export const EN_WORDS_TIER2 = ${JSON.stringify(byTier[2].join(' '))};
export const EN_WORDS_TIER3 = ${JSON.stringify(byTier[3].join(' '))};
`;
fs.writeFileSync(path.join(outDir, 'words.en.ts'), out);

const copyright = path.join(finalDir, '..', 'Copyright');
if (fs.existsSync(copyright)) {
  fs.copyFileSync(copyright, path.join(outDir, 'LICENSE-SCOWL.txt'));
}
console.log(
  `Wrote ${seen.size} words (tier1 ${byTier[1].length}, tier2 ${byTier[2].length}, tier3 ${byTier[3].length})`,
);
